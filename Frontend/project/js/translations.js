// Get current language
function getCurrentLanguage() {
  if (typeof Store === 'undefined') return 'en';
  const settings = Store.get('scms_settings', {});
  const language = settings.language || 'English';
  
  if (language === 'Gujarati') return 'gu';
  if (language === 'Hindi') return 'hi';
  if (language === 'Marathi') return 'mr';
  return 'en';
}

// Translate key
function t(key) {
  const lang = getCurrentLanguage();
  const text = Translations[lang]?.[key];
  return text || Translations.en[key] || key;
}

// Change language
function changeLanguage(langName) {
  if (typeof Store === 'undefined') {
    alert('Storage not available. Please reload the page.');
    return;
  }
  
  const settings = Store.get('scms_settings', {});
  settings.language = langName;
  Store.set('scms_settings', settings);
  
  // Show toast and reload
  if (typeof Toast !== 'undefined') {
    Toast.show(`Language changed to ${langName}`, 'success');
  }
  setTimeout(() => location.reload(), 500);
}

window.Translations = Translations;
window.getCurrentLanguage = getCurrentLanguage;
window.t = t;
window.changeLanguage = changeLanguage;
